/**
 * Golden QR symbols, produced by an independent encoder — the `qrcode` Python package
 * (kazuhikoarase lineage), level M, byte mode, at the mask the format's own penalty rules pick.
 *
 * They are frozen here rather than generated at test time so the suite stays offline and
 * dependency-free (CLAUDE.md: tests never touch the network). Regenerate with:
 *
 *   pip install qrcode
 *   python3 - <<'PY'
 *   import qrcode
 *   from qrcode.constants import ERROR_CORRECT_M
 *   q = qrcode.QRCode(error_correction=ERROR_CORRECT_M, box_size=1, border=0, mask_pattern=<mask>)
 *   q.add_data(qrcode.util.QRData(text.encode(), mode=qrcode.util.MODE_8BIT_BYTE))
 *   q.make(fit=True)
 *   PY
 *
 * `mask` records which mask the reference was forced to, because the library's own automatic
 * choice does not always land on the lowest-penalty mask and ours does.
 */

